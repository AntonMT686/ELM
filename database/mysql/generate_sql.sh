#!/usr/bin/env bash
# Regenerates the SQL files in this folder from the Alembic migrations and the minimal seed.
# Needs: backend virtualenv with requirements installed, and a scratch MySQL/MariaDB where $SCRATCH_URL's user may
# create and drop the database named in it (never point this at proflow_uat).
#   SCRATCH_URL="mysql+pymysql://root:pw@127.0.0.1:3306/elm_scratch?charset=utf8mb4" MYSQL="mysql -uroot" MYSQLDUMP="mysqldump -uroot" database/mysql/generate_sql.sh
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HERE/../.." && pwd)
: "${SCRATCH_URL:?set SCRATCH_URL}"; MYSQL=${MYSQL:-mysql}; MYSQLDUMP=${MYSQLDUMP:-mysqldump}
DB=$(echo "$SCRATCH_URL" | sed -E 's|.*/([^/?]+)(\?.*)?$|\1|')
[ "$DB" != "proflow_uat" ] || { echo "refusing to use proflow_uat as the scratch database"; exit 1; }
PY=${PY:-$ROOT/backend/.venv/bin/python}
REV=$(cd "$ROOT/backend" && "$PY" -c "from alembic.config import Config; from alembic.script import ScriptDirectory; print(ScriptDirectory.from_config(Config('alembic.ini')).get_current_head())")

{
  echo "-- ADA-ELM schema for MySQL / MariaDB, Alembic head: $REV. Generated by generate_sql.sh, do not edit by hand."
  echo "-- Run INSIDE the existing database:   mysql -u <admin> -p proflow_uat < 01_elm_schema.sql"
  echo "-- Creates only elm_* tables (and elm_alembic_version). Legacy PMS tables are not read, changed or dropped."
  echo "-- Preferred alternative that also handles later upgrades: python -m app.dbsetup  (see Docs/RUNNING.md)."
  echo "SET NAMES utf8mb4;"
  echo "SET default_storage_engine = InnoDB;"
  echo
  (cd "$ROOT/backend" && ELM_DATABASE_URL="$SCRATCH_URL" "$PY" -m alembic upgrade head --sql 2> >(grep -v "^INFO" >&2))
} > "$HERE/01_elm_schema.sql"

$MYSQL -e "DROP DATABASE IF EXISTS \`$DB\`; CREATE DATABASE \`$DB\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
(cd "$ROOT/backend" && ELM_DATABASE_URL="$SCRATCH_URL" ELM_SEED_DEMO_DATA=false ELM_ADMIN_PASSWORD='ChangeMe@123' ELM_ENVIRONMENT=uat "$PY" -m app.dbsetup >/dev/null)
TABLES=$($MYSQL -N -e "select table_name from information_schema.tables where table_schema='$DB' and table_name like 'elm\\_%' and table_name<>'elm_alembic_version' order by table_name" | tr '\n' ' ')
{
  echo "-- ADA-ELM reference data (production bootstrap), Alembic head: $REV. Generated by generate_sql.sh."
  echo "-- Run AFTER 01_elm_schema.sql, on an EMPTY ELM schema:   mysql -u <admin> -p proflow_uat < 02_elm_reference_data.sql"
  echo "-- Contents: root organisation, roles and permissions, process domains, document types, three published workflows,"
  echo "-- the shared plan phases and ONE user: admin / ChangeMe@123  ->  sign in and change this password immediately."
  echo "-- No demo people or projects. For demo data use: ELM_SEED_DEMO_DATA=true python -m app.dbsetup"
  echo "SET NAMES utf8mb4;"
  echo "SET FOREIGN_KEY_CHECKS = 0;"
  $MYSQLDUMP --no-create-info --skip-triggers --complete-insert --skip-extended-insert --skip-add-locks --skip-comments --compact "$DB" $TABLES
  echo "SET FOREIGN_KEY_CHECKS = 1;"
} > "$HERE/02_elm_reference_data.sql"
$MYSQL -e "DROP DATABASE IF EXISTS \`$DB\`;"
echo "Wrote $HERE/01_elm_schema.sql and $HERE/02_elm_reference_data.sql (head $REV)"
